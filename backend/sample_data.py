def _gen_points(
    rng: random.Random,
    centers: List[tuple[float, float, str, str, str, int]],
) -> List[Dict[str, Any]]:
    """根据 (cx, cy, side, kind, place, count) 生成逼真的雷达散点。"""
    pts: List[Dict[str, Any]] = []
    r_counter = 1
    for cx, cy, side, kind, place, count in centers:
        spread = 2.4 if kind == "position" else 1.8
        for _ in range(count):
            pts.append(
                {
                    "x": round(max(4.0, min(96.0, rng.gauss(cx, spread))), 1),
                    "y": round(max(4.0, min(96.0, rng.gauss(cy, spread))), 1),
                    "side": side,
                    "kind": kind,
                    "place": place,
                    "round": ((r_counter - 1) % 24) + 1,
                }
            )
            r_counter += 1
    return pts


